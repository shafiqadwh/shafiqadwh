import crypto from 'node:crypto';

const COOKIE = 'guest_device';
const YEAR_MS = 365 * 24 * 60 * 60 * 1000;

/**
 * ให้เครื่องของแขกแต่ละคนมีรหัสประจำเครื่อง เก็บใน cookie
 *
 * ทำไมต้องมี: ตัวจำกัดอัตราเดิมนับตามไอพี ซึ่งพังทันทีในงานจริง เพราะ
 *   - แขกที่ต่อ WiFi ของสถานที่จัดงาน ออกเน็ตด้วยไอพีสาธารณะเดียวกันทั้งหมด
 *   - แขกที่ใช้ 4G/5G ก็ยังใช้ CGNAT ของค่าย ไอพีเดียวกันเป็นร้อยเครื่อง
 * ผลคือพอมีคนอัพครบโควตา แขกที่เหลือ "ทั้งหมด" ที่อยู่หลังไอพีนั้นถูกปฏิเสธ
 * ทดสอบแล้วเจอจริง: อัพได้ 199 ครั้งแล้วทุกคนโดน 429 และเขียนคำอวยพรได้แค่ 30 ครั้ง
 *
 * รหัสประจำเครื่องลบทิ้งเองได้ จึงกันคนตั้งใจก่อกวนไม่ได้ — แต่ตัวจำกัดนี้มีไว้
 * กันเครื่องที่รวนหรือคนกดรัว ไม่ได้มีไว้กันการโจมตี ส่วนการกันการโจมตีจริง
 * ยังมีเพดานรวมต่อไอพีอีกชั้นที่ตั้งไว้สูงพอไม่ให้ไปโดนแขกปกติ
 */
export function deviceMiddleware(req, res, next) {
  let id = req.cookies?.[COOKIE];

  if (!/^[a-f0-9]{32}$/.test(id ?? '')) {
    id = crypto.randomBytes(16).toString('hex');
    res.cookie(COOKIE, id, {
      httpOnly: true,
      sameSite: 'lax',
      secure: req.protocol === 'https',
      maxAge: YEAR_MS,
    });
  }

  req.deviceId = id;
  next();
}

/** คีย์ที่ใช้นับโควตา — ใช้รหัสเครื่องถ้ามี ถ้าเบราว์เซอร์ปฏิเสธ cookie ก็ถอยไปใช้ไอพี */
export const byDevice = (req) => (req.deviceId ? `d:${req.deviceId}` : `ip:${req.ip}`);
export const byIp = (req) => `ip:${req.ip}`;
