/**
 * ผ่านขั้น "จัดท่า" ซึ่งคั่นระหว่างกดเริ่มกับการนับถอยหลัง
 *
 * ขั้นนี้มีภาพสดค้างไว้ให้กลุ่มใหญ่จัดแถวทัน (สามวินาทีไม่พอ เจอจริงตอนลองใช้)
 * และมีนาฬิกาพาไปถ่ายเองเมื่อหมดเวลา — แต่นาฬิกานั้นตั้งไว้เป็นนาทีสำหรับคนจริง
 * เทสต์รอไม่ไหว จึงกดแทนแขกเสมอ · ตัวนาฬิกาเองมีเทสต์ของมันใน idle.test.js
 *
 * รับได้ทั้งกรณีที่จอไปหยุดที่หน้าเก็บเงินก่อน (โหมดจ่ายก่อนถ่าย) — เจอหน้านั้น
 * แล้วไม่ทำอะไร ปล่อยให้เทสต์จัดการเรื่องเงินเอง แล้วค่อยเรียกซ้ำทีหลังได้
 */
export async function passFraming(page, control = page) {
  // รอ "ขั้นไหนก็ได้ที่แปลว่าเดินหน้าไปแล้ว" — เรียกตัวช่วยนี้ผิดที่จะได้ไม่ค้าง
  // ยี่สิบวินาทีเปล่า ๆ แล้วทำให้หาสาเหตุยากกว่าเดิม
  await page.waitForSelector([
    'body[data-stage="frame"]', 'body[data-stage="pay"]',
    'body[data-stage="shoot"]', 'body[data-stage="review"]',
  ].join(', '), { timeout: 20000 });
  if (await page.getAttribute('body', 'data-stage') !== 'frame') return false;
  // `control` = หน้าต่างที่จะกดปุ่ม · จอช่างภาพกดแทนแขกได้ ปุ่มชื่อเดียวกันทั้งสองจอ
  await control.locator('#go').click();
  return true;
}
