/**
 * ฟิลเตอร์อัตโนมัติ — **วัดภาพก่อน แล้วค่อยตัดสินว่าจะแต่งเท่าไร**
 *
 * นี่คือความต่างทั้งหมดระหว่าง "auto" กับ "พรีเซ็ตอีกตัวหนึ่ง" · ภาพที่ถ่ายมาดีอยู่แล้ว
 * ต้องถูกแตะน้อยมากหรือไม่ถูกแตะเลย ซึ่งเป็นวิธีเดียวที่ทำให้ "สวยขึ้นชัดเจน" กับ
 * "ไม่แต่งเยอะ" เป็นจริงพร้อมกันได้ · ทุกค่าในไฟล์นี้จึงมีเพดาน และเพดานทุกตัวมีเหตุผล
 * เขียนกำกับไว้ว่าถ้าเกินไปแล้วภาพเสียยังไง
 *
 * ลำดับตามที่ห้องแต่งภาพจริงทำ: **แก้ให้ถูกก่อน แล้วค่อยใส่สไตล์**
 * ไฟล์นี้ทำเฉพาะส่วน "แก้ให้ถูก" — สมดุลแสงขาว ระดับแสง และความอิ่มสี
 * ส่วนสไตล์ (ฟิล์ม ขาวดำ สดใส) เป็นเอฟเฟคแยกที่เลือกเองใน effects.js
 *
 * ⚠️ **สิ่งที่ตั้งใจไม่ทำ: การเกลี่ยผิว** · มันคือสิ่งที่ทำให้ภาพดูพลาสติก และเป็น
 * ความเสียหายที่แก้กลับไม่ได้หลังกระดาษออกมาแล้ว · บูธที่ขายรูปสวยไม่ใช่บูธที่
 * ลบใบหน้าคนทิ้ง
 *
 * ⚠️ **`sharp.gamma()` ใช้ยกกลางภาพไม่ได้** — วัดแล้วบนไปป์ไลน์นี้มันแทบไม่ขยับ
 * อะไรเลย (128 → 127 ที่ gamma 1.15 และ 1.4 ให้ผลเท่ากัน) เพราะมันถูกออกแบบมา
 * ให้ครอบการ resize ไม่ใช่ใช้ปรับโทน · แผนเดิมมีขั้นยกกลางภาพด้วยแกมมา ตัดทิ้งไป
 * หลังวัด แทนที่จะปล่อยไว้ให้ดูเหมือนมีคนคิดมาแล้วทั้งที่ไม่ทำอะไร
 * ส่วน `modulate({ brightness })` ก็เป็นการคูณธรรมดาที่ตัดไฮไลท์ทิ้ง (224 → 250
 * ที่ 1.1) จึงไม่ใช้เหมือนกัน — การดึงระดับด้วย `linear` ครั้งเดียวคุมได้ตรงกว่า
 */

/** เอาเฉพาะพิกเซลสว่างสุดกี่ส่วนมาหาสมดุลแสงขาว */
const HIGHLIGHT_FRACTION = 0.1;

/**
 * เกนของสมดุลแสงขาวขยับได้มากสุด ±6% เทียบกับช่องเขียว
 *
 * งานแต่งจัดใต้ไฟทังสเตนหรือโคมเหลืองทั้งงานเป็นเรื่องปกติ และ **ความอุ่นนั้นคือ
 * บรรยากาศที่เจ้าภาพตั้งใจ** ไม่ใช่ความผิดพลาดที่ต้องลบทิ้ง
 *
 * เริ่มไว้ที่ ±12% แล้วเรนเดอร์ออกมาดู — **ภาพที่ถ่ายมาดีอยู่แล้วถูกดันจนโคมไฟ
 * กลายเป็นสีฟ้า** เพราะเพดานคุมทีละช่อง แดงลงไป 0.88 น้ำเงินขึ้นไป 1.12 ระยะห่าง
 * จริงระหว่างสองช่องจึงเป็น 27% ไม่ใช่ 12% · ที่ ±6% ระยะห่างสูงสุดเหลือ 13%
 * ซึ่งพอแก้ผิวที่เหลืองเกินได้ แต่ไม่พอจะลบสีของฉากทิ้ง
 *
 * **ยึดช่องเขียวเป็นหลัก** ไม่ใช่ค่าเฉลี่ยสามช่อง — เขียวเป็นตัวหลักของความสว่าง
 * (0.7152 ใน Rec.709) ตรึงไว้แล้วการแก้สีจะไม่ไปเปลี่ยนความสว่างของภาพตามไปด้วย
 */
const WB_MAX_GAIN = 0.06;

/** ต่างจากกลางน้อยกว่า 2% = ตาคนแยกไม่ออก แตะไปก็เสี่ยงเปล่า ๆ */
const WB_DEADZONE = 0.02;

/**
 * **ขับด้วยจุดขาว ไม่ใช่ยืดช่วงให้เต็ม**
 *
 * นี่คือหัวใจของทั้งไฟล์ และเป็นข้อที่เขียนผิดรอบแรกจนเห็นกับตาว่าพัง
 *
 * auto-levels แบบตำรา (ยืด [p0.5, p99.5] ให้เต็ม [0, 255]) ตั้งอยู่บนสมมติฐานว่า
 * **ภาพนี้ควรมีทั้งดำสนิทและขาวสนิท** ซึ่งไม่จริงกับภาพคนใต้แสงนุ่ม ๆ ในเต็นท์
 * ผลที่วัดได้จากภาพทดสอบ: เงาที่ p0.5 ถูกดันไปที่ **−7** (ตันสนิท) และค่ากลางทั้งภาพ
 * **ตกจาก 71 เหลือ 38** — ภาพใต้แสงน้อยกลับมืดลงกว่าเดิม ตรงข้ามกับที่ควรเป็นทุกทาง
 * (สาเหตุตรง ๆ คือ `a` ชนเพดานแล้ว แต่ `b` ยังคิดจากเจตนาที่ทำไม่ได้แล้ว)
 *
 * สิ่งที่ช่างแต่งภาพทำจริงคือ **แก้ค่าแสงก่อน แล้วค่อยดูว่าต้องเพิ่มดำไหม**
 * ยกจุดขาวไปที่เป้า แล้วดึงจุดดำลงได้นิดเดียวเท่านั้น · เงาที่ลอยขึ้นมาหน่อยคือ
 * เงาที่นุ่มและให้อภัยผิวคน ซึ่งคือสิ่งที่ภาพบูธต้องการ ไม่ใช่คอนทราสต์จัด
 */
const WHITE_TARGET = 248;

/** ดำต่ำสุดที่ยอมให้ไปถึง — ต่ำกว่านี้พิมพ์ออกมาเป็นก้อนดำไม่มีรายละเอียด */
const BLACK_FLOOR = 4;

/**
 * ดึงจุดดำลงได้มากสุดกี่ระดับ
 *
 * ตัวเลขนี้คือตัวกันไม่ให้เกิดอาการที่เจอรอบแรก · ภาพหม่นได้คอนทราสต์คืนมาพอให้
 * รู้สึกว่า "ใส" แต่ไม่มีทางกลายเป็นภาพที่เงาตันไม่ว่าภาพต้นทางจะเป็นยังไง
 */
const MAX_BLACK_SHIFT = 14;

/**
 * ดึงระดับได้มากสุด 1.8 เท่า
 *
 * เพดานนี้ไม่ได้มีไว้กันไฮไลท์ไหม้ (จุดขาวคุมเรื่องนั้นอยู่แล้วโดยวิธีคิด) แต่มีไว้
 * กันการดึงภาพที่มืดจนเกินกู้ ซึ่งจะได้แต่จุดรบกวนที่ถูกขยายขึ้นมาเต็มภาพ
 */
const MAX_STRETCH = 1.8;

/** ช่องสีช่องไหนพุ่งเกินนี้หลังแก้ = สีนั้นไหม้ ต้องลดการดึงลงจนไม่เกิน */
const CHANNEL_CEILING = 252;

/**
 * ความอิ่มสี — **ภาพจืดเพิ่มมาก ภาพสีจัดเพิ่มน้อย**
 *
 * ใกล้เคียงกับ vibrance ของโปรแกรมแต่งภาพ แต่ไม่ใช่อันเดียวกัน: vibrance จริง
 * ดูทีละพิกเซล ส่วนนี่ดูค่าเฉลี่ยทั้งภาพแล้วเลือกตัวคูณตัวเดียว · เขียนไว้ตรง ๆ
 * ดีกว่าเรียกมันว่า vibrance แล้วให้คนคาดหวังผิด
 *
 * เพดาน 1.12 เพราะเกินกว่านั้นผิวคนเริ่มออกส้ม ซึ่งเห็นชัดที่สุดบนกระดาษพิมพ์
 */
const SAT_FLAT = 0.2;
const SAT_RICH = 0.45;
const SAT_MAX = 1.12;
const SAT_MIN = 1.02;

/** ค่าน้ำหนักความสว่างตาม Rec.709 — ตรงกับที่ตาคนรับรู้มากกว่าการเฉลี่ยสามช่องเท่ากัน */
const LUMA = [0.2126, 0.7152, 0.0722];

const clamp = (value, low, high) => Math.min(high, Math.max(low, value));

/** ค่าที่ตำแหน่งเปอร์เซ็นไทล์ที่ขอ จากฮิสโตแกรม 256 ช่อง */
function percentile(histogram, total, fraction) {
  const want = total * fraction;
  let seen = 0;
  for (let value = 0; value < 256; value += 1) {
    seen += histogram[value];
    if (seen >= want) return value;
  }
  return 255;
}

/**
 * วัดภาพหนึ่งใบจากพิกเซลดิบ
 *
 * แยกจากการแต่งโดยตั้งใจ — ป้อนพิกเซลที่รู้ค่าแน่นอนเข้าไปแล้วตรวจตัวเลขที่ได้
 * จึงทำได้โดยไม่ต้องแตะ sharp เลย และไม่ต้องมีรูปถ่ายจริงมาเป็นตัวตั้ง
 *
 * `raw` คือ RGB เรียงต่อกัน (ไม่มีช่องความโปร่งใส)
 */
export function measure(raw, channels = 3) {
  const pixels = Math.floor(raw.length / channels);
  const lum = new Uint32Array(256);
  const perChannel = [new Uint32Array(256), new Uint32Array(256), new Uint32Array(256)];

  let lumTotal = 0;
  let satTotal = 0;
  let satCount = 0;

  for (let i = 0; i < pixels; i += 1) {
    const at = i * channels;
    const r = raw[at];
    const g = raw[at + 1];
    const b = raw[at + 2];

    perChannel[0][r] += 1;
    perChannel[1][g] += 1;
    perChannel[2][b] += 1;

    const y = Math.round(LUMA[0] * r + LUMA[1] * g + LUMA[2] * b);
    lum[y] += 1;
    lumTotal += y;

    // ความอิ่มสีแบบ HSV · ข้ามพิกเซลที่มืดจนสีไม่มีความหมาย ไม่งั้นฉากหลังดำ
    // จะลากค่าเฉลี่ยลงจนภาพที่สีจัดถูกอ่านว่าจืด
    const max = Math.max(r, g, b);
    if (max >= 24) {
      satTotal += (max - Math.min(r, g, b)) / max;
      satCount += 1;
    }
  }

  /*
   * สมดุลแสงขาวจาก **พิกเซลสว่างที่สุด 10%** ไม่ใช่ค่าเฉลี่ยทั้งภาพ (gray-world)
   *
   * gray-world พังทันทีที่ฉากหลังเป็นสีเดียวเต็มเฟรม ซึ่งคือบูธที่มี backdrop
   * ทุกบูธ — ฉากหลังแดงทั้งผืนจะถูกอ่านว่า "ภาพนี้อมแดง" แล้วโดนถอดแดงออกจนผิว
   * เขียว · ส่วนบริเวณสว่างมักเป็นแสงสะท้อนหรือของสีขาว ซึ่งบอกสีของ *แสง* ได้ตรงกว่า
   *
   * ตัดพิกเซลที่ช่องใดช่องหนึ่งไหม้แล้ว (≥ 250) ทิ้ง — มันไม่เหลือข้อมูลสีให้อ่าน
   */
  const cut = percentile(lum, pixels, 1 - HIGHLIGHT_FRACTION);
  const sum = [0, 0, 0];
  let bright = 0;
  for (let i = 0; i < pixels; i += 1) {
    const at = i * channels;
    const r = raw[at];
    const g = raw[at + 1];
    const b = raw[at + 2];
    /*
     * **มากกว่าเส้นตัด ไม่ใช่มากกว่าหรือเท่ากับ** — ต่างกันแค่นี้แต่ชี้ขาดในกรณีที่
     * ต้องกันจริง ๆ · ฉากหลังสีเดียวผืนใหญ่ทำให้เส้นตัดตกลงมาทับค่าของฉากหลังพอดี
     * แล้วฉากหลังทั้งผืนก็ไหลเข้ามาเป็น "บริเวณสว่าง" กลบพิกเซลกลางสีที่มีอยู่จริง
     * (วัดแล้ว: ฉากแดง 90 พิกเซล + แสงสะท้อนสีกลาง 10 พิกเซล → ถอดแดงออกจนผิดทั้งภาพ)
     */
    if (Math.round(LUMA[0] * r + LUMA[1] * g + LUMA[2] * b) <= cut) continue;
    if (r >= 250 || g >= 250 || b >= 250) continue;
    sum[0] += r;
    sum[1] += g;
    sum[2] += b;
    bright += 1;
  }

  return {
    pixels,
    meanLuma: pixels ? lumTotal / pixels : 0,
    meanSat: satCount ? satTotal / satCount : 0,
    /*
     * ค่าเฉลี่ยของบริเวณสว่าง · `null` เมื่ออ่านไม่ได้
     *
     * เหลือน้อยกว่า 0.5% ของภาพก็ถือว่าอ่านไม่ได้ — ตัวอย่างไม่กี่พิกเซลบอกสีของ
     * แสงทั้งฉากไม่ได้ และการเดาจากตัวอย่างน้อย ๆ อันตรายกว่าการไม่แก้เลย
     * (ภาพเรียบทั้งใบหรือภาพไหม้ทั้งใบก็ตกลงมาที่นี่ ซึ่งถูกต้อง: ไม่มีอะไรให้อ้างอิง)
     */
    highlight: bright / Math.max(1, pixels) >= 0.005
      ? sum.map((total) => total / bright)
      : null,
    low: percentile(lum, pixels, 0.005),
    high: percentile(lum, pixels, 0.995),
    channelHigh: perChannel.map((histogram) => percentile(histogram, pixels, 0.995)),
  };
}

/**
 * แปลงผลการวัดเป็นค่าที่จะสั่ง sharp — บริสุทธิ์ ไม่แตะรูป
 *
 * คืน `linear` เป็นค่าต่อช่องสี เพราะ **สมดุลแสงขาวกับการดึงระดับยุบเป็นคำสั่ง
 * เดียวกันได้พอดี**: ปรับสมดุลคือคูณ (v × gain) ดึงระดับคือคูณแล้วบวก (a × v + b)
 * ต่อกันได้เป็น (a × gain) × v + b ซึ่งคือ `linear([...], [...])` ครั้งเดียว
 * ทำสองคำสั่งแยกกันไม่ได้ผลต่างกัน แต่ยุบแล้วอ่านง่ายกว่าและพลาดลำดับไม่ได้
 * (วัดแล้ว: sharp ทำตามลำดับภายในของมันเอง ไม่ใช่ลำดับที่เราเรียก)
 */
export function planFrom(stats) {
  const gains = [1, 1, 1];

  if (stats.highlight) {
    const target = stats.highlight[1];
    for (let c = 0; c < 3; c += 1) {
      const wanted = stats.highlight[c] > 0 ? target / stats.highlight[c] : 1;
      gains[c] = clamp(wanted, 1 - WB_MAX_GAIN, 1 + WB_MAX_GAIN);
    }
    // ทั้งสามช่องเบี้ยวไปน้อยกว่าเส้นตายก็ปล่อยไว้ทั้งชุด ไม่ใช่แก้เฉพาะบางช่อง
    if (gains.every((gain) => Math.abs(gain - 1) < WB_DEADZONE)) {
      gains[0] = 1;
      gains[1] = 1;
      gains[2] = 1;
    }
  }

  /*
   * ค่าแสง: ยกจุดขาวไปที่เป้า · **ห้ามลดทอน** ภาพที่สว่างพออยู่แล้วปล่อยไว้ตามเดิม
   * ไม่ใช่บีบให้เข้าสูตร
   */
  let a = stats.high > 0 ? clamp(WHITE_TARGET / stats.high, 1, MAX_STRETCH) : 1;

  /*
   * จุดดำ: ดึงลงได้นิดเดียว และคิดจากค่าที่ยกแล้วเสมอ
   *
   * ผูก `b` ไว้กับ `a` ตัวจริงที่จะใช้ ไม่ใช่กับเจตนาก่อนโดนเพดาน — ความผิดพลาด
   * รอบแรกอยู่ตรงนี้เป๊ะ ๆ และมันไม่ปรากฏในตัวเลขตัวไหนเลยจนกระทั่งเรนเดอร์ออกมาดู
   */
  // `|| 0` กัน -0 ที่ออกมาจากการติดลบของศูนย์ — ไม่มีผลกับภาพ แต่ทำให้ค่าที่จดไว้อ่านง่าย
  let b = -clamp(a * stats.low - BLACK_FLOOR, 0, MAX_BLACK_SHIFT) || 0;

  /*
   * กันช่องสีเดี่ยวไหม้
   *
   * จุดขาวคิดจากความสว่างรวม แต่ช่องแดงของภาพที่อมแดงอยู่แล้วจะสูงกว่านั้น และ
   * ยังต้องคูณเกนของสมดุลแสงขาวอีกชั้น · ไม่ตรวจตรงนี้แล้วเสื้อแดงกับผิวคนจะ
   * กลายเป็นก้อนสีตันที่ไม่มีรายละเอียดเหลือ ทั้งที่ภาพรวมดูไม่ไหม้
   */
  for (let c = 0; c < 3; c += 1) {
    const peak = stats.channelHigh[c] * gains[c];
    if (peak <= 0) continue;
    if (a * peak + b > CHANNEL_CEILING) {
      a = Math.max(1, (CHANNEL_CEILING - b) / peak);
      b = -clamp(a * stats.low - BLACK_FLOOR, 0, MAX_BLACK_SHIFT) || 0;
    }
  }

  /*
   * ความอิ่มสี — ไล่ระหว่างสองหมุด ภาพจืดได้เพิ่มเต็ม ภาพสีจัดได้แค่แตะ
   */
  const range = SAT_RICH - SAT_FLAT;
  const position = clamp((stats.meanSat - SAT_FLAT) / range, 0, 1);
  const saturation = SAT_MAX - position * (SAT_MAX - SAT_MIN);

  const linear = {
    a: gains.map((gain) => a * gain),
    b: [b, b, b],
  };

  return {
    linear,
    saturation,
    // เกนของสมดุลแสงขาวล้วน ๆ แยกจากการดึงระดับ — ไว้ให้เทสต์กับ log อ่านได้ว่า
    // ส่วนไหนของ `linear` มาจากการแก้สี ส่วนไหนมาจากการแก้แสง
    gains,
    // ไม่มีอะไรขยับพอให้เห็น = ภาพนี้ถ่ายมาดีอยู่แล้ว บอกไว้ให้เทสต์กับ log ตรวจได้
    touched: a !== 1 || b !== 0
      || gains.some((gain) => gain !== 1)
      || Math.abs(saturation - 1) >= 0.005,
  };
}
