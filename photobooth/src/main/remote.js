import { KEY_ACTIONS } from '../core/keys.js';

/**
 * ปุ่มที่ไปไม่ถึงหน้าจอ — ต้องยึดระดับระบบถึงจะได้
 *
 * ทางหลักของรีโมทคือหน้าจอรับปุ่มเอง (ดู booth.js / operator.js) ซึ่งพอสำหรับ
 * รีโมทเกือบทุกตัว เพราะบูธเปิดเต็มจอค้างทั้งงาน หน้าต่างจึงโฟกัสตลอด
 *
 * ที่เหลือคือปุ่มที่เดสก์ท็อป (GNOME/KDE) ยึดไว้ก่อนแล้ว — ปุ่มเสียงบน Linux
 * หน้าต่างไม่มีวันเห็น ต้องแย่งยึดระดับระบบเท่านั้น · เปิดทางนี้ไว้ให้เฉพาะปุ่ม
 * ที่ตั้งใจ **ค่าเริ่มต้นไม่จดอะไรเลย** เพราะการยึด Enter ไว้ทั้งเครื่องแปลว่า
 * โปรแกรมอื่นบนเครื่องนั้นใช้ปุ่มนั้นไม่ได้ไปจนกว่าจะปิดบูธ
 *
 * จดไม่สำเร็จต้องบอกให้รู้ ไม่ใช่เงียบแล้วปล่อยให้ไปกดรีโมทหน้างานแล้วงงว่าทำไมไม่ติด
 */
export function registerGlobalKeys(globalShortcut, keys, press) {
  const taken = [];
  for (const key of keys) {
    if (!KEY_ACTIONS[key]) continue;
    if (globalShortcut.register(key, () => press({ key }))) taken.push(key);
    else console.warn(`[remote] จดปุ่ม ${key} ไม่ได้ — มีโปรแกรมอื่นยึดไว้อยู่`);
  }
  return taken;
}
