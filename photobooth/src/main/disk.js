import fs from 'node:fs/promises';

/**
 * เตือนก่อนดิสก์เต็ม — ไม่ใช่หลังจากที่รอบของแขกล้มไปแล้ว
 *
 * บูธเก็บรูปดิบทุกใบของทุกรอบไว้ถาวร และ **ไม่มีอะไรลบมันเลย** โดยตั้งใจ
 * (รูปของแขกคืนเดียวที่ไม่มีวันถ่ายซ้ำได้ ไม่ใช่ของที่โปรแกรมจะลบเองตามใจ)
 * แปลว่าพื้นที่ลดลงทุกงานและไม่มีวันกลับมาเองจนกว่าเจ้าของจะย้ายออก
 *
 * วัดจากภาพที่รายละเอียดเต็มเฟรมแบบภาพถ่ายจริง (ไม่ใช่ภาพสีเรียบซึ่งบีบอัดได้เกินจริง):
 *
 *   เว็บแคม 1080p   รูป 0.75 MB/ใบ   →  ~3.8 MB ต่อรอบ  →  200 รอบ  0.75 GB
 *   DSLR 18MP       รูป 6.45 MB/ใบ   →  ~20.6 MB ต่อรอบ →  200 รอบ  4.03 GB
 *
 * **จังหวะที่ดิสก์เต็มคือจังหวะที่แย่ที่สุดเท่าที่จะเป็นไปได้**: โหมดจ่ายก่อนถ่าย
 * รับเงินไปแล้ว แล้วการประกอบแผ่นล้มตอนเขียนไฟล์ · รอบนั้นกู้ได้ (ตั๋วยังอยู่)
 * แต่รอบถัดไปก็ล้มเหมือนกัน และทุกรอบหลังจากนั้นด้วย จนกว่าจะมีคนไปลบไฟล์ —
 * ซึ่งไม่มีทางเกิดขึ้นกลางงานที่คนต่อแถวอยู่
 *
 * กติกาของไฟล์นี้: **บอกให้รู้ ไม่ห้าม** · ห้ามถ่ายเพราะพื้นที่ใกล้หมดคือการปิดบูธ
 * ด้วยมือของตัวเองทั้งที่ยังถ่ายได้อีกเป็นร้อยรอบ · และ **วัดไม่ได้ = เงียบ**
 * ไม่ใช่ล้ม — ตัวเตือนที่ทำให้รอบของแขกพังคือตัวเตือนที่แย่กว่าไม่มี
 */

const GB = 1024 * 1024 * 1024;
const MB = 1024 * 1024;

/** ขนาดต่อรอบที่วัดมาจริง — ใช้แปลงพื้นที่ที่เหลือเป็น "อีกกี่รอบ" ซึ่งคนตัดสินใจได้ */
export const ROUND_BYTES = Object.freeze({
  webcam: 4 * MB,
  dslr: 21 * MB,
});

/**
 * เตือนเมื่อเหลือน้อยกว่า 2 GB
 *
 * เลือกจากตัวเลขที่วัดมา ไม่ใช่ตัวเลขกลม ๆ: 2 GB คือราว 100 รอบของโหมด DSLR
 * ซึ่งเป็นโหมดที่กินที่มากที่สุด · เหลือ 100 รอบคือยังขายต่อได้ทั้งคืนสบาย ๆ
 * แต่รู้ตัวทันว่าต้องย้ายไฟล์ออกก่อนงานหน้า — ซึ่งคือสิ่งที่การเตือนควรทำให้ได้
 *
 * `BOOTH_DISK_WARN_BYTES` มีไว้ให้เทสต์บังคับสถานะ "ใกล้เต็ม" บนเครื่องที่ดิสก์ว่าง
 * ได้จริง ไม่ใช่ให้ตั้งใช้งานจริง
 */
export const WARN_BYTES = Number(process.env.BOOTH_DISK_WARN_BYTES) || 2 * GB;

/** ขั้นวิกฤต — เหลือเท่านี้คือใกล้จะล้มจริงในไม่กี่รอบ ไม่ใช่เรื่องของงานหน้าแล้ว */
export const CRITICAL_BYTES = 400 * MB;

/**
 * พื้นที่ว่างของดิสก์ที่โฟลเดอร์นี้อยู่ · คืน `null` เมื่อวัดไม่ได้
 *
 * `fs.statfs` ใช้ได้ทั้ง Windows/macOS/Linux ตั้งแต่ Node 18 · โฟลเดอร์ที่ยังไม่มี
 * อยู่จริงทำให้มันโยน จึงต้องรับไว้ — ตอนเปิดบูธครั้งแรกโฟลเดอร์ยังไม่ถูกสร้าง
 */
export async function freeBytes(dir, statfs = fs.statfs) {
  try {
    const { bavail, bsize } = await statfs(dir);
    const free = Number(bavail) * Number(bsize);
    return Number.isFinite(free) && free >= 0 ? free : null;
  } catch {
    return null;
  }
}

const round1 = (n) => Math.round(n * 10) / 10;

/**
 * ข้อความเตือนสำหรับจอช่างภาพ — `null` เมื่อยังไม่ต้องเตือน
 *
 * เขียนเป็น "อีกกี่รอบ" ด้วย เพราะ "เหลือ 1.4 GB" ไม่ได้บอกคนหน้าบูธว่าควรทำอะไร
 * ส่วน "พอสำหรับอีกราว 70 รอบ" ตัดสินใจได้ทันทีว่าจะขายต่อหรือหยุดย้ายไฟล์ก่อน
 */
export async function diskWarning(dir, {
  perRound = ROUND_BYTES.webcam,
  warnBytes = WARN_BYTES,
  criticalBytes = CRITICAL_BYTES,
  statfs,
} = {}) {
  const free = await freeBytes(dir, statfs);
  if (free === null || free >= warnBytes) return null;

  const rounds = Math.floor(free / perRound);
  const left = free >= GB ? `${round1(free / GB)} GB` : `${Math.round(free / MB)} MB`;
  const critical = free < criticalBytes;

  return {
    critical,
    freeBytes: free,
    rounds,
    text: critical
      ? `พื้นที่เหลือ ${left} — อีกราว ${rounds} รอบเท่านั้น · ย้ายรูปรอบเก่าออกเดี๋ยวนี้`
      : `พื้นที่เหลือ ${left} — พอสำหรับอีกราว ${rounds} รอบ · ย้ายรูปรอบเก่าออกก่อนงานหน้า`,
  };
}
